"""WeSpeaker frontend parity against independent Kaldi reference features.

The fixture contains synthetic PCM and mean-normalised features generated by
kaldi-native-fbank 1.23.1, using 16 kHz / 25 ms / 10 ms, Hamming, dither=0,
80 mel bins, low_freq=20, snip_edges=True, and use_energy=False. Full options
and the generator wheel SHA-256 are stored in the fixture's provenance field.
The reference package is only needed to regenerate the fixture.
"""
from pathlib import Path

import numpy as np
import pytest

import speaker_diarization as sd


@pytest.mark.parametrize("name", ["noise", "modulated", "quiet"])
def test_fbank_matches_kaldi_reference(name):
    fixture = Path(__file__).parent / "fixtures" / "wespeaker_fbank_reference.npz"
    with np.load(fixture, allow_pickle=False) as reference:
        samples = reference["pcm_" + name].astype(np.float32) / 32768.0
        original = samples.copy()
        features = sd._kaldi_fbank(samples)

        assert features is not None
        assert features.dtype == np.float32
        assert features.shape == (51, 80)
        # Allow FFT/float32 implementation rounding, not frontend differences.
        np.testing.assert_allclose(
            features, reference["features_" + name], atol=2e-4, rtol=0,
        )
        np.testing.assert_array_equal(samples, original)
        np.testing.assert_allclose(features.mean(axis=0), 0, atol=2e-5, rtol=0)


@pytest.mark.parametrize("n_samples", [0, 399, 8000, 8239])
def test_fbank_rejects_clips_with_fewer_than_50_complete_frames(n_samples):
    assert sd._kaldi_fbank(np.zeros(n_samples, dtype=np.float32)) is None


@pytest.mark.parametrize("n_samples, n_frames", [(8240, 50), (8400, 51), (16000, 98)])
def test_fbank_silence_is_finite_and_uses_complete_frames(n_samples, n_frames):
    features = sd._kaldi_fbank(np.zeros(n_samples, dtype=np.float32))
    assert features is not None
    assert features.shape == (n_frames, 80)
    assert np.isfinite(features).all()
    np.testing.assert_allclose(features, 0, atol=2e-5, rtol=0)
